import {_electron,expect} from '@playwright/test';
import electron from 'electron';
import {mkdtempSync,rmSync,writeFileSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {tsImport} from 'tsx/esm/api';
const {HealthStore}=await tsImport('../electron/core/store.ts',import.meta.url);
const {FoodCatalog}=await tsImport('../electron/core/nutrition.ts',import.meta.url);
const {memoryDependency}=await tsImport('../electron/core/memory.ts',import.meta.url);
const {EVALUATION_EXAMPLE}=await tsImport('../src/shared/evaluation.ts',import.meta.url);
const vault=mkdtempSync(path.join(tmpdir(),'bodyjournal-v05-ui-')),errors=[];
const evaluationFile=path.join(vault,'synthetic-evaluation.json'),exampleFile=path.join(vault,'saved-example.json');
let app;
try{
  const store=new HealthStore(vault,new FoodCatalog([]),path.join(vault,'inbox'),false);
  const earlier=new Date(Date.now()-86400000).toISOString(),now=new Date().toISOString();
  const original=store.saveMemory({kind:'fact',text:'我喜欢晚上训练',topicKey:'training.time_preference',startsAt:earlier,expiresAt:null,sourceIds:[],active:true,confirmed:true,evidence:[{quote:'我喜欢晚上训练',origin:'user',at:earlier}]});
  store.putMessage({id:'synthetic-question-old',role:'user',text:'我平时什么时候训练？',createdAt:earlier,status:'complete',sources:[],provider:'chatgpt',stale:false});
  store.putMessage({id:'synthetic-answer-old',role:'assistant',text:'合成旧回答：你偏好晚上训练。',createdAt:earlier,status:'complete',sources:[],provider:'chatgpt',stale:false,memoryDependency:[memoryDependency(original)]});
  const current=store.saveMemory({...original,text:'以后改成早晨训练',startsAt:now,evidence:[{quote:'以后改成早晨训练',origin:'user',at:now}]},original.id);
  store.putMessage({id:'synthetic-question-new',role:'user',text:'以后改成早晨训练',createdAt:now,status:'complete',sources:[],provider:'chatgpt',stale:false});
  store.putMessage({id:'synthetic-answer-new',role:'assistant',text:'合成当前回答：你的新偏好是早晨训练。',createdAt:now,status:'complete',sources:[],provider:'chatgpt',stale:false,memoryDependency:[memoryDependency(current)]});
  store.close();writeFileSync(evaluationFile,JSON.stringify(EVALUATION_EXAMPLE));
  const launchArgs=process.env.BODYJOURNAL_APP?[]:[process.cwd()];
  app=await _electron.launch({executablePath:process.env.BODYJOURNAL_APP??electron,args:process.env.ELECTRON_NO_SANDBOX==='1'?['--no-sandbox',...launchArgs]:launchArgs,env:{...process.env,HEALTH_TEST_VAULT:vault,HEALTH_DEMO:'0'},timeout:30000});
  const page=await app.firstWindow();page.on('pageerror',e=>errors.push(e.message));
  await page.getByRole('navigation',{name:'主导航'}).waitFor();
  const oldAnswer=page.locator('.message.assistant').filter({hasText:'合成旧回答'});
  await expect(oldAnswer.locator('.stale-label')).toContainText('依据已变化或过期');
  const currentAnswer=page.locator('.message.assistant').filter({hasText:'合成当前回答'});
  await currentAnswer.getByText('本次使用的记忆（1）',{exact:true}).click();
  await expect(currentAnswer.getByText('以后改成早晨训练',{exact:true})).toBeVisible();
  await currentAnswer.getByRole('button',{name:'查看当前记忆',exact:true}).click();
  let modal=page.getByRole('dialog');
  await modal.getByText(/来源与修改历史 · 版本/).click();
  await expect(modal.getByText('我喜欢晚上训练',{exact:true})).toBeVisible();
  await expect(modal.locator('.original-text').filter({hasText:'以后改成早晨训练'})).toBeVisible();
  await modal.getByRole('button',{name:'关闭',exact:true}).click();
  await page.getByRole('navigation').getByRole('button',{name:'我的档案',exact:true}).click();
  const row=page.locator('.memory-row').filter({hasText:'以后改成早晨训练'});
  await row.getByText(/来源与修改历史 · 版本/).click();
  await expect(row.getByText('我喜欢晚上训练',{exact:true})).toBeVisible();
  await row.getByRole('button',{name:'编辑记忆',exact:true}).click();
  modal=page.getByRole('dialog');
  await expect(modal).toBeVisible();
  await modal.getByLabel('内容',{exact:false}).fill('以后改成中午训练');
  await modal.getByRole('button',{name:'确认保存',exact:true}).click();
  await expect(modal).toHaveCount(0);
  await page.getByRole('navigation').getByRole('button',{name:'助理',exact:true}).click();
  await expect(currentAnswer.locator('.stale-label')).toContainText('依据已变化或过期');
  await page.getByRole('button',{name:'连接与数据',exact:true}).click();
  const panel=page.getByRole('region',{name:'精度评测'});
  await expect(panel.getByRole('button',{name:'选择评测文件',exact:true})).toBeVisible();
  await app.evaluate(({dialog},files)=>{
    dialog.showOpenDialog=async()=>({canceled:false,filePaths:[files.evaluationFile]});
    dialog.showSaveDialog=async()=>({canceled:false,filePath:files.exampleFile});
  },{evaluationFile,exampleFile});
  await panel.getByRole('button',{name:'选择评测文件',exact:true}).click();
  await expect(panel.getByRole('heading',{name:'合成示例：标签、称量与未知参考',exact:true})).toBeVisible();
  await expect(panel).toContainText('合成数据，只验证流程');
  await expect(panel.getByRole('cell',{name:'2.5 kcal',exact:false})).toBeVisible();
  await panel.getByText('区间、重复波动与食物匹配明细',{exact:true}).click();
  await expect(panel.getByRole('columnheader',{name:'热量重复标准差',exact:true})).toBeVisible();
  await panel.getByText('同样本比较：candidate 与 baseline',{exact:true}).click();
  await expect(panel.getByRole('cell',{name:'-52.5 kcal',exact:true})).toBeVisible();
  await panel.getByRole('button',{name:'保存合成示例',exact:true}).click();
  await expect(panel.getByRole('status')).toContainText('合成示例已保存');
  if(JSON.parse(readFileSync(exampleFile,'utf8')).synthetic!==true)throw new Error('Saved example is not marked synthetic');
  await page.setViewportSize({width:860,height:650});
  await panel.scrollIntoViewIfNeeded();
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Evaluation panel overflows narrow window');
  await page.screenshot({path:path.join(tmpdir(),'bodyjournal-v05-evaluation.png')});
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('v0.5 isolated UI passed: memory evidence/history, correction invalidation, native-selected offline evaluation, paired metrics, synthetic example save and narrow layout.');
}catch(error){if(app){const page=await app.firstWindow();await page.screenshot({path:path.join(tmpdir(),'bodyjournal-v05-failure.png')}).catch(()=>{});console.error('v05 UI failure context:',errors,await page.locator('[role="dialog"]').allTextContents());}throw error;}
finally{if(app)await app.close().catch(()=>{});rmSync(vault,{recursive:true,force:true});}
