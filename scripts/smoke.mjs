import { _electron as electronTest, expect } from '@playwright/test';
import electron from 'electron';
import { mkdtempSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
const root=process.cwd();
const executablePath=process.env.BODYJOURNAL_APP??electron;
const launchArgs=process.env.BODYJOURNAL_APP?[]:[root];
// 受限 CI/沙箱环境里 Chromium 无法初始化自己的 OS sandbox，仅测试时可用 ELECTRON_NO_SANDBOX=1 关闭；不影响打包应用。
const sandboxArgs=process.env.ELECTRON_NO_SANDBOX==='1'?['--no-sandbox']:[];
const vault=mkdtempSync(path.join(tmpdir(),'bodyjournal-ui-'));
mkdirSync('evidence',{recursive:true});
let app;
const errors=[];
async function launch(demo=false){
 app=await electronTest.launch({executablePath,args:[...sandboxArgs,...launchArgs],env:{...process.env,HEALTH_TEST_VAULT:vault,HEALTH_DEMO:demo?'1':'0'},timeout:30000});
 const page=await app.firstWindow();
 page.on('pageerror',e=>errors.push(e.message));
 await page.getByRole('navigation',{name:'主导航'}).waitFor();
 return page;
}
try {
 let page=await launch(false);
 await expect(page.getByRole('heading',{name:'今天，给身体留一点线索。'})).toBeVisible();
 await page.getByRole('button',{name:'记身体',exact:true}).click();
 await page.getByRole('spinbutton',{name:'体重（kg）'}).fill('72.4');
 await page.getByRole('spinbutton',{name:'腰围（cm）'}).fill('81.2');
 await page.getByRole('button',{name:'保存记录',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 let snapshot=await page.evaluate(()=>window.health.invoke('snapshot'));
 if(snapshot.records.length!==1||snapshot.records[0].body.weightKg!==72.4)throw new Error('Body UI save failed');
 await page.getByRole('navigation').getByRole('button',{name:'记录'}).click();
 await page.getByRole('button',{name:/72.4 kg/}).first().click();
 await page.getByRole('button',{name:'修改原始记录',exact:true}).click();
 await page.getByRole('dialog').getByLabel('体重 kg',{exact:true}).fill('72.1');
 await page.getByRole('button',{name:'保存修改',exact:true}).click();
 await page.getByRole('button',{name:'撤销上次修改',exact:true}).click();
 snapshot=await page.evaluate(()=>window.health.invoke('snapshot'));if(snapshot.records[0].body.weightKg!==72.4)throw new Error('UI undo failed');
 await page.getByRole('dialog').getByRole('button',{name:'关闭',exact:true}).click();
 await page.getByRole('button',{name:'导入笔记',exact:true}).click();
 await page.getByRole('textbox',{name:'历史训练笔记'}).fill('2026-10-20\n卧推 60kg 3组×8次\n2026-10-22\n卧推 62.5kg 3组×8次');
 await page.getByRole('button',{name:'预览拆分结果'}).click();
 await page.getByRole('button',{name:'确认导入 2 次训练'}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('navigation').getByRole('button',{name:'趋势',exact:true}).click();
 await page.getByRole('button',{name:'训练表现',exact:true}).click();
 await expect(page.getByRole('cell',{name:'1500',exact:true})).toBeVisible();
 const groups=await page.locator('select[aria-label="训练动作"] optgroup').evaluateAll(es=>es.map(e=>e.getAttribute('label')));
 if(!groups.length||!groups.includes('胸'))throw new Error('训练动作缺少部位分组: '+groups.join(','));
 await page.getByRole('button',{name:'整理动作名称'}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 const archived=async()=>page.evaluate(async()=>((await window.health.invoke('snapshot')).exerciseRules?.archived??[]).length);
 await page.getByRole('button',{name:'归档',exact:true}).first().click();
 await expect.poll(archived).toBe(1);
 await page.getByRole('button',{name:'取消归档',exact:true}).first().click();
 await expect.poll(archived).toBe(0);
 await page.getByRole('button',{name:'取消',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('navigation').getByRole('button',{name:'我的档案',exact:true}).click();
 await expect(page.getByRole('button',{name:'整理记忆',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'添加记忆',exact:true}).click();
 await page.getByRole('dialog').getByLabel('内容',{exact:true}).fill('测试：周三晚上可以训练。');
 await page.getByRole('button',{name:'确认保存',exact:true}).click();
 await expect(page.getByText('测试：周三晚上可以训练。',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'添加常用食物',exact:true}).click();
 const foodDialog=page.getByRole('dialog');
 await foodDialog.getByLabel('名称').fill('乳清蛋白粉');
 await foodDialog.getByLabel('标签每份数量').fill('30');
 await foodDialog.getByLabel('能量 kcal / 标签份').fill('120');
 await foodDialog.getByLabel('蛋白质 g / 标签份').fill('24');
 await foodDialog.getByLabel('碳水 g / 标签份').fill('3');
 await foodDialog.getByLabel('脂肪 g / 标签份').fill('1.5');
 await foodDialog.getByRole('button',{name:'确认保存',exact:true}).click();
 await expect(page.getByText('每份 30g',{exact:false})).toBeVisible();
 if(await page.evaluate(()=>typeof window.require)!=='undefined')throw new Error('Renderer unexpectedly has Node');
 await app.close();
 page=await launch(false);
 snapshot=await page.evaluate(()=>window.health.invoke('snapshot'));
 if(snapshot.records.length!==3||!snapshot.memories.some(m=>m.text==='测试：周三晚上可以训练。'))throw new Error('Restart persistence failed');
 await app.close();
 const demoVault=mkdtempSync(path.join(tmpdir(),'bodyjournal-demo-ui-'));
 app=await electronTest.launch({executablePath,args:[...sandboxArgs,...launchArgs],env:{...process.env,HEALTH_TEST_VAULT:demoVault,HEALTH_DEMO:'1'},timeout:30000});
 page=await app.firstWindow();page.on('pageerror',e=>errors.push(e.message));await page.getByRole('navigation',{name:'主导航'}).waitFor();
 for(const [name,id] of [['助理','assistant'],['记录','records'],['趋势','trends'],['我的档案','profile']]){
  await page.getByRole('navigation').getByRole('button',{name,exact:name!=='记录'}).click();
  await page.screenshot({path:`evidence/${id}.png`});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);if(overflow)throw new Error(`Horizontal overflow: ${name}`);
 }
 await page.getByRole('button',{name:'连接与数据',exact:true}).click();
 // Public screenshots omit machine-specific paths, including isolated temporary inboxes.
 await page.screenshot({path:'evidence/settings.png',mask:[page.locator('.path-box')],maskColor:'#eaf3ed'});
 await app.close();rmSync(demoVault,{recursive:true,force:true});
 if(errors.length)throw new Error(errors.join('\n'));
 console.log('UI checks passed: create, edit, undo, historical import, trends, memory, restart persistence, renderer isolation; five screenshots captured.');
}finally{if(app)await app.close().catch(()=>{});rmSync(vault,{recursive:true,force:true});}
